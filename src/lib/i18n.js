function detectLocale() {
  const stored = localStorage.getItem('rendez-vous-locale');
  if (stored && translations[stored]) return stored;
  const browser = navigator.language?.slice(0, 2);
  if (browser && translations[browser]) return browser;
  return 'en';
}

export const locale = $state({ value: detectLocale() });

export const locales = Object.keys(translations);

export const localeLabels = { fr: 'FR', en: 'EN', es: 'ES' };

export function setLocale(lang) {
  locale.value = lang;
  localStorage.setItem('rendez-vous-locale', lang);
  document.documentElement.lang = lang;
}

export function t(key, params = {}) {
  let str = translations[locale.value]?.[key] || translations.en[key] || key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replace(`{${k}}`, v);
  }
  return str;
}
